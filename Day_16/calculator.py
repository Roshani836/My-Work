class Calculator:
    
    def add (self, a ,b):
        print("Add: ", a + b)
    
    def sub (self, a ,b):
        print("Substraction: ", a - b)
    
    def mul (self, a ,b):
        print("Multiplication: ", a * b)
    
    def div (self, a ,b):
        print("Divide: ", a / b)
    
c1 = Calculator()

c1.add(10 ,20)
c1.sub(10 ,20)
c1.mul(10 ,20)
c1.div(10 ,20)


    
    